from pathlib import Path
import json,hashlib
names=['ArcAccount','ArcFactory','IntentVault','IntentVaultFactory','QuotaAllocator','QuotaLeaf','AdapterRegistry','TransferPayAdapter']
out={}
for name in names:
 p=Path('evm/out')/(name+'.sol')/(name+'.json')
 if not p.exists() and name in ['QuotaLeaf']:p=Path('evm/out/QuotaAllocator.sol')/(name+'.json')
 if not p.exists() and name=='IntentVaultFactory':p=Path('evm/out/IntentVault.sol')/(name+'.json')
 data=json.loads(p.read_text())
 out[name]={'abi':data['abi'],'bytecode':data['bytecode']['object'],'deployedBytecodeTemplate':data['deployedBytecode']['object'],'immutableReferences':data['deployedBytecode'].get('immutableReferences',{})}
Path('packages/arc/src/artifacts.ts').write_text('// Generated by scripts/continuity/export-artifacts.py from pinned Foundry compiler output.\nexport const artifacts = '+json.dumps(out,separators=(',',':'))+' as const;\n')
Path('reports/artifact-hashes.json').write_text(json.dumps({n:hashlib.sha256(json.dumps(v,sort_keys=True).encode()).hexdigest() for n,v in out.items()},indent=2))
